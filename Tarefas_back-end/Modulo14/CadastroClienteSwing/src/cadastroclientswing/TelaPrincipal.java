    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linhaSelecionada = tabelaClientes.getSelectedRow();
        
        if(linhaSelecionada >= 0){
            int result = JOptionPane.showConfirmDialog(this, "Deseja Excluir este cliente", "Confirmação",
                            JOptionPane.YES_NO_OPTION,
                            JOptionPane.QUESTION_MESSAGE);
           
            if (result == JOptionPane.YES_OPTION) {
                
                Long cpf = (Long) tabelaClientes.getValueAt(linhaSelecionada, 1);
                this.clienteDAO.excluir(cpf);
                modelo.removeRow(linhaSelecionada);
                
                JOptionPane.showMessageDialog(null, "Cliente excluído com sucesso", "Excluir",JOptionPane.INFORMATION_MESSAGE);
                limparCampos();
            }
        }
        
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        int linhaSelecionada = tabelaClientes.getSelectedRow();
        if(linhaSelecionada >= 0) {
            Long cpf =(Long) tabelaClientes.getValueAt(linhaSelecionada, 1);
            String nome = txtNome.getText();
            String tel = txtTel.getText();
            String end = txtEnd.getText();
            String numero = txtNumero.getText();
            String cidade = txtCidade.getText();
            String estado = txtEstado.getText();
            
            if (!isCAmposValidos(nome, cpf.toString(), tel, end, numero, cidade,estado)) {
                JOptionPane.showMessageDialog(this, "Há Campos não preenchidos");
                return;
            }
            
            Cliente clienteNovo = new Cliente(nome, cpf.toString(), tel, end, numero, cidade, estado);
            this.clienteDAO.alterar(clienteNovo);
            
            modelo.removeRow(linhaSelecionada);
            modelo.addRow(new Object[]{clienteNovo.getNome(), clienteNovo.getCpf(), clienteNovo.getEnd(), clienteNovo.getTel()});
            JOptionPane.showMessageDialog(null, "Cliente atualizado com sucesso", "Alterar", JOptionPane.INFORMATION_MESSAGE);
            limparCampos();
        }
        else {
            JOptionPane.showMessageDialog(null, "Nenhum cliente selecionado","Alterar", JOptionPane.INFORMATION_MESSAGE);
        }
        
    }//GEN-LAST:event_btnAtualizarActionPerformed

