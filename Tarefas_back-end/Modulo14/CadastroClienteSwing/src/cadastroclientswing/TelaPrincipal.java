    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String nome = txtNome.getText();
        String cpf = txtCPF.getText();
        String end = txtEnd.getText();
        String numero = txtNumero.getText();
        String cidade = txtCidade.getText();
        String estado = txtEstado.getText();
        String tel = txtTel.getText();
        
        if (!isCAmposValidos(nome, cpf, end, numero, cidade, estado, tel)) {
        JOptionPane.showMessageDialog(null, "Há campos não preenchidos", "Erro", JOptionPane.INFORMATION_MESSAGE);
        return;
        }
        
        Cliente cliente = new Cliente(nome,cpf,tel,end,numero,cidade,estado);
        Boolean isCadastro = clienteDAO.cadastrar(cliente);
        
        if(isCadastro) {
            modelo.addRow(new Object[]{cliente.getNome(), cliente.getCpf(), cliente.getEnd(), cliente.getTel()});
            limparCampos();
            JOptionPane.showMessageDialog(null, "Olá "+nome, "Bem-Vindo", JOptionPane.INFORMATION_MESSAGE);
        }
        
        
    }//GEN-LAST:event_btnSalvarActionPerformed

